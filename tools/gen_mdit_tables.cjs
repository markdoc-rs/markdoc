'use strict';
// Generates the tables the markdown-it port (src/markdown_it/common/) takes from
// markdown-it's dependencies, so they match the JavaScript exactly:
//
//   entities.rs  every named character reference `decodeHTMLStrict` decodes (`&name;`),
//                enumerated by walking the package's own decode trie with its EntityDecoder
//   ucmicro.rs   the code points uc.micro's P and S regexes accept, evaluated as
//                markdown-it's isPunctCharCode does: `P.test(fromCodePoint(c))` for every
//                c in 0..=0x10FFFF (surrogates as lone code units)
//
// Usage: node tools/gen_mdit_tables.cjs <node_modules dir> [--check] [--oracle <markdoc dist/index.js>]
//   <node_modules dir> holds entities (8.x) and uc.micro (3.x).
//   --check   compares instead of writing; exits 1 when a checked-in file differs.
//   --oracle  also checks the tables against the markdown-it bundled in upstream Markdoc
//             (its own copies of entities and uc.micro): every table entry, every trie
//             prefix that is not an entity, and isPunctCharCode for every code point.
// The packages are only read and required, never modified.

const fs = require('fs');
const path = require('path');

const args = process.argv.slice(2);
const check = args.includes('--check');
const oracleIdx = args.indexOf('--oracle');
const oracle = oracleIdx >= 0 ? args[oracleIdx + 1] : null;
const nm = args.find((a, i) => !a.startsWith('--') && (oracleIdx < 0 || i !== oracleIdx + 1));
if (!nm) {
  console.error('usage: node tools/gen_mdit_tables.cjs <node_modules dir> [--check] [--oracle <markdoc dist/index.js>]');
  process.exit(2);
}
const outDir = path.join(__dirname, '..', 'src', 'markdown_it', 'common');

const pkgVersion = (name) => JSON.parse(fs.readFileSync(path.join(nm, name, 'package.json'), 'utf8')).version;

// Rust string literal for a JS string: printable ASCII as is, everything else \u{..}.
function rustStr(s) {
  let out = '"';
  for (const ch of s) {
    const cp = ch.codePointAt(0);
    if (ch === '"' || ch === '\\') out += '\\' + ch;
    else if (cp >= 0x20 && cp < 0x7f) out += ch;
    else out += `\\u{${cp.toString(16)}}`;
  }
  return out + '"';
}

function genEntities() {
  const dec = require(path.resolve(nm, 'entities', 'dist', 'decode.js'));
  const { EntityDecoder, htmlDecodeTree, DecodingMode, decodeHTMLStrict } = dec;
  const ALNUM = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
  // write() returns -1 while the input is still a path in the trie, the consumed length
  // for a complete entity, 0 otherwise.
  const write = (s) => {
    const d = new EntityDecoder(htmlDecodeTree, () => {});
    d.startEntity(DecodingMode.Strict);
    return d.write(s, 0);
  };
  const found = [];
  const prefixes = [];
  const stack = [''];
  while (stack.length) {
    const prefix = stack.pop();
    for (const c of ALNUM) {
      const name = prefix + c;
      if (write(name) !== -1) continue;
      stack.push(name);
      prefixes.push(name);
      if (write(name + ';') > 0) {
        const value = decodeHTMLStrict('&' + name + ';');
        if (value === '&' + name + ';') throw new Error(`${name}: trie says entity, decodeHTMLStrict disagrees`);
        found.push([name, value]);
      }
    }
  }
  // byte order, as Rust's &str Ord (names are ASCII)
  found.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

  let rs = '';
  rs += `// @generated by tools/gen_mdit_tables.cjs from entities ${pkgVersion('entities')}. Do not edit.\n`;
  rs += '//! The named character references `decodeHTMLStrict` (entities package) decodes: `&name;`\n';
  rs += '//! for each name below, sorted by name. Strict mode only decodes semicolon-terminated\n';
  rs += '//! references, so the legacy forms without `;` are not here.\n\n';
  rs += `/// (name without \`&\` and \`;\`, decoded value), sorted by name.\n`;
  rs += '#[rustfmt::skip]\n';
  rs += `pub static ENTITIES: [(&str, &str); ${found.length}] = [\n`;
  for (const [name, value] of found) rs += `    (${rustStr(name)}, ${rustStr(value)}),\n`;
  rs += '];\n\n';
  rs += '/// The decoded value of `&name;`, if `name` is a named character reference.\n';
  rs += 'pub fn lookup(name: &str) -> Option<&\'static str> {\n';
  rs += '    ENTITIES\n';
  rs += '        .binary_search_by(|(n, _)| (*n).cmp(name))\n';
  rs += '        .ok()\n';
  rs += '        .map(|i| ENTITIES[i].1)\n';
  rs += '}\n';
  return { rs, found, prefixes };
}

function genUcmicro() {
  const uc = require(path.resolve(nm, 'uc.micro'));
  // markdown-it's utils.fromCodePoint (never throws)
  const fromCodePoint = (c) => {
    if (c > 0xffff) {
      c -= 0x10000;
      return String.fromCharCode(0xd800 + (c >> 10), 0xdc00 + (c & 0x3ff));
    }
    return String.fromCharCode(c);
  };
  const ranges = (re) => {
    const out = [];
    let start = -1;
    for (let c = 0; c <= 0x110000; c++) {
      const m = c <= 0x10ffff && re.test(fromCodePoint(c));
      if (m && start < 0) start = c;
      if (!m && start >= 0) {
        out.push([start, c - 1]);
        start = -1;
      }
    }
    return out;
  };
  const hex = (n) => '0x' + n.toString(16).toUpperCase();
  const table = (name, re) => {
    const r = ranges(re);
    let s = `/// Code points (inclusive ranges) for which \`ucmicro.${name}.test(fromCodePoint(c))\`.\n`;
    s += '#[rustfmt::skip]\n';
    s += `pub static ${name}: [(u32, u32); ${r.length}] = [\n`;
    for (let i = 0; i < r.length; i += 6) {
      s += '    ' + r.slice(i, i + 6).map(([a, b]) => `(${hex(a)}, ${hex(b)})`).join(', ') + ',\n';
    }
    return s + '];\n\n';
  };
  let rs = '';
  rs += `// @generated by tools/gen_mdit_tables.cjs from uc.micro ${pkgVersion('uc.micro')}. Do not edit.\n`;
  rs += "//! uc.micro's P (punctuation) and S (symbol) classes, as markdown-it's `isPunctChar`\n";
  rs += '//! evaluates them: the regexes are not Unicode-aware, so astral characters match as\n';
  rs += '//! surrogate pairs and a lone surrogate never matches.\n\n';
  rs += table('P', uc.P);
  rs += table('S', uc.S);
  rs += 'fn in_ranges(ranges: &[(u32, u32)], c: u32) -> bool {\n';
  rs += '    ranges\n';
  rs += '        .binary_search_by(|&(lo, hi)| {\n';
  rs += '            if hi < c {\n';
  rs += '                std::cmp::Ordering::Less\n';
  rs += '            } else if lo > c {\n';
  rs += '                std::cmp::Ordering::Greater\n';
  rs += '            } else {\n';
  rs += '                std::cmp::Ordering::Equal\n';
  rs += '            }\n';
  rs += '        })\n';
  rs += '        .is_ok()\n';
  rs += '}\n\n';
  rs += '/// `ucmicro.P.test(fromCodePoint(c))`.\n';
  rs += 'pub fn is_p(c: u32) -> bool {\n    in_ranges(&P, c)\n}\n\n';
  rs += '/// `ucmicro.S.test(fromCodePoint(c))`.\n';
  rs += 'pub fn is_s(c: u32) -> bool {\n    in_ranges(&S, c)\n}\n';
  return { rs, P: ranges(uc.P), S: ranges(uc.S) };
}

const ent = genEntities();
const ucm = genUcmicro();

if (oracle) {
  // markdown-it's utils from the bundle upstream Markdoc ships (engine-only instance)
  const Markdoc = require(path.resolve(oracle));
  const utils = new (new Markdoc.Tokenizer().parser.constructor)().utils;
  let bad = 0;
  for (const [name, value] of ent.found) {
    if (utils.unescapeAll('&' + name + ';') !== value) { console.error(`oracle disagrees on &${name};`); bad++; }
  }
  const names = new Set(ent.found.map((f) => f[0]));
  for (const p of ent.prefixes) {
    if (!names.has(p) && utils.unescapeAll('&' + p + ';') !== '&' + p + ';') { console.error(`oracle decodes &${p};`); bad++; }
  }
  // flatten to a lookup array for speed
  const ps = new Uint8Array(0x110000);
  for (const [a, b] of ucm.P.concat(ucm.S)) for (let c = a; c <= b; c++) ps[c] = 1;
  for (let c = 0; c <= 0x10ffff; c++) {
    if (utils.isPunctCharCode(c) !== (ps[c] === 1)) { if (bad < 20) console.error(`oracle disagrees on isPunctCharCode(${c.toString(16)})`); bad++; }
  }
  console.error(`oracle check: ${ent.found.length} entities, ${ent.prefixes.length} trie prefixes, 0x110000 code points: ${bad} disagreements`);
  if (bad) process.exit(1);
}

const files = { 'entities.rs': ent.rs, 'ucmicro.rs': ucm.rs };
let stale = 0;
for (const [name, text] of Object.entries(files)) {
  const file = path.join(outDir, name);
  if (check) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current !== text) {
      console.error(`${file} is not what the generator produces`);
      stale++;
    }
  } else {
    fs.writeFileSync(file, text);
    console.error(`wrote ${file}`);
  }
}
process.exit(stale ? 1 : 0);
